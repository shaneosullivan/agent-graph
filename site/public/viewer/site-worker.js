"use strict";

// The shared viewer's data, worked out off the page's main thread, so
// reducing a long log doesn't hold the page up: started by site-source.js,
// it reads the log's chunks from the API, and computes graphs with Agent
// Graph's reducer, compiled to WebAssembly (the same code as the CLI).
//
// It's sent `{ id, op, … }` and replies `{ id, … }`:
//
//   { op: "pull", log }   reads the chunks of log `log` it doesn't have yet:
//                         `{ added }`, whether any events arrived, or
//                         `{ reload: true }` if the page should load again
//   { op: "query", request }  `{ result }`: the WebAssembly's reply to
//                         `request` (see wasm/src/lib.rs)
//
// or, if that fails, `{ id, error }`.
//
// Hand-written; everything else in this folder is generated by
// scripts/sync-viewer.mjs.

const enc = new TextEncoder();
const dec = new TextDecoder();
const exact = new TextDecoder("utf-8", {ignoreBOM: true});

let wasm = null;

// Strings cross into WebAssembly as UTF-8 bytes in its memory.
function put(text) {
  return putBytes(enc.encode(text));
}

function putBytes(bytes) {
  const ptr = wasm.alloc(bytes.length);
  new Uint8Array(wasm.memory.buffer, ptr, bytes.length).set(bytes);
  return [ptr, bytes.length];
}

function call(request) {
  const [ptr, len] = put(JSON.stringify(request));
  const out = wasm.query(ptr, len);
  wasm.dealloc(ptr, len);
  const n = wasm.result_len();
  const text = dec.decode(new Uint8Array(wasm.memory.buffer, out, n));
  wasm.dealloc(out, n);
  return JSON.parse(text);
}

// Fetches the chunks we don't have yet. Returns how many events arrived, or
// null if the page should load again.
let after = "";
// Where the next text read should start. A log's chunks are stored one
// after another, so a read that starts anywhere else, with a keyframe,
// means its start was trimmed as we read it (a live share keeps only its
// last two keyframes' worth), perhaps only partway so far: what we hold is
// broken, so we start again from that keyframe (a trim cuts only at one).
// A gap that isn't a trim's (a log written with one) is read past.
let next = null;
async function pull(log) {
  let added = 0;
  for (;;) {
    const res = await fetch(`/api/logs/${log}/content?after=${after}`, {
      cache: "no-store",
    });
    if (res.status === 401) return null; // the password cookie expired; the page asks again
    if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
    // Its bytes, as stored: a byte-order mark at its start is kept (text()
    // would drop it, and so miscount where the next read starts).
    const bytes = new Uint8Array(await res.arrayBuffer());
    const first = res.headers.get("x-first-chunk");
    if (bytes.length && first !== null) {
      const line = bytes.indexOf(10);
      const head = exact.decode(line < 0 ? bytes : bytes.subarray(0, line));
      if (next !== null && Number(first) !== next && startsWithKeyframe(head)) {
        wasm.reset();
        added++;
      }
      next = Number(first) + bytes.length;
    }
    if (bytes.length) {
      const [ptr, len] = putBytes(bytes);
      added += wasm.append(ptr, len);
      wasm.dealloc(ptr, len);
    }
    after = res.headers.get("x-last-chunk") || after;
    if (res.headers.get("x-more") !== "1") return added;
  }
}

function startsWithKeyframe(text) {
  const end = text.indexOf("\n");
  try {
    return JSON.parse(end < 0 ? text : text.slice(0, end)).type === "keyframe";
  } catch {
    return false;
  }
}

async function loadWasm(url) {
  if (WebAssembly.instantiateStreaming) {
    try {
      return (await WebAssembly.instantiateStreaming(fetch(url), {})).instance
        .exports;
    } catch {
      // Falls through: some servers send the wrong content type.
    }
  }
  const bytes = await (await fetch(url)).arrayBuffer();
  return (await WebAssembly.instantiate(bytes, {})).instance.exports;
}

const loading = loadWasm("/viewer/agent_graph.wasm").then(
  exports => (wasm = exports),
);
loading.catch(() => {}); // said in reply to each request instead

self.onmessage = async ({data}) => {
  const {id, op} = data;
  try {
    await loading;
    if (op === "pull") {
      const added = await pull(data.log);
      postMessage(added === null ? {id, reload: true} : {id, added: added > 0});
    } else if (op === "query") {
      postMessage({id, result: call(data.request)});
    } else {
      throw new Error(`no op ${op}`);
    }
  } catch (err) {
    postMessage({id, error: err.message || String(err)});
  }
};
