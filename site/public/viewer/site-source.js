"use strict";

// Feeds the shared viewer (app.js, the same page `agent-graph view` serves)
// from this site instead of a local server. A worker (site-worker.js) reads
// a log's text from the API in chunks, and computes graphs and timelines
// with Agent Graph's reducer, compiled to WebAssembly: the same code as the
// CLI, off the page's main thread, so a long log doesn't hold the page up.
//
// At /watch (`config.shares`), an account can be sharing from several
// computers or cloud instances at once, each its own log. The list shows
// every session of every one of them: those of logs not open, from the
// summaries each share sends the site (GET /api/watch/shares), each labelled
// with the computer it's on. Opening one reads its own log, in a worker of
// its own, so each has its own timeline, and one big log doesn't hold up
// the rest.
//
// Hand-written; everything else in this folder is generated by
// scripts/sync-viewer.mjs.

(async () => {
  const config = JSON.parse(
    document.getElementById("agent-graph-config").textContent,
  );

  /** A log, read by a worker of its own. */
  function openLog(id, url) {
    const worker = new Worker("/viewer/site-worker.js");
    const waiting = new Map();
    let asked = 0;
    worker.onmessage = ({data}) => {
      const request = waiting.get(data.id);
      if (!request) return;
      waiting.delete(data.id);
      if (data.error !== undefined) request.reject(new Error(data.error));
      else request.resolve(data);
    };
    // It couldn't start (its script didn't load, say): nothing it was asked will come.
    worker.onerror = e => {
      const error = new Error(e.message || "Couldn't start the worker");
      for (const request of waiting.values()) request.reject(error);
      waiting.clear();
    };
    function ask(message) {
      return new Promise((resolve, reject) => {
        const n = asked++;
        waiting.set(n, {resolve, reject});
        worker.postMessage({id: n, ...message});
      });
    }
    const log = {
      id,
      async call(request) {
        return (await ask({op: "query", request})).result;
      },
      async reply(request) {
        const result = await log.call(request);
        if (result && result.error)
          throw new Error(`${result.status} ${result.error}`);
        return result;
      },
      // Has the worker fetch the chunks it doesn't have yet. Returns
      // whether any events arrived.
      async pull() {
        // (A log that's a file of its own, as an example is, is read from its `url`.)
        const {added, reload} = await ask({op: "pull", log: id, url});
        if (reload) {
          location.reload(); // the password cookie expired; the page asks again
          return false;
        }
        return added;
      },
    };
    // Read once, before it's first asked anything.
    log.ready = log.pull();
    return log;
  }

  // The log the page opened with, and (at /watch) the others, as opened.
  const first = openLog(config.id, config.url);
  const logs = new Map([[config.id, first]]);
  await first.ready;
  // The log last asked for a graph: the one being looked at, which is
  // followed live.
  let current = first;

  // At /watch: every live share, and which one each session is in.
  let shares = [];
  let shareOf = new Map();
  async function loadShares() {
    if (!config.shares) return false;
    const res = await fetch("/api/watch/shares", {cache: "no-store"});
    if (!res.ok) return false;
    const next = (await res.json()).shares || [];
    const changed = JSON.stringify(next) !== JSON.stringify(shares);
    shares = next;
    shareOf = new Map();
    for (const share of shares)
      for (const session of Object.keys(share.summary || {}))
        if (!shareOf.has(session)) shareOf.set(session, share.id);
    return changed;
  }
  await loadShares().catch(() => false);

  /** The log node `id` (or its session) is in: the one open, if none's known. */
  function logFor(id) {
    if (!id) return current;
    const share = shareOf.get(String(id).split("/")[0]);
    if (!share || share === current.id) return current;
    let log = logs.get(share);
    if (!log) {
      log = openLog(share);
      logs.set(share, log);
    }
    return log;
  }

  /** Where each share is, by its id, for labelling its sessions. */
  const hostOf = id => shares.find(s => s.id === id)?.host || "";

  /**
   * Whether share `id` was a cloud instance that's gone: Codex's and Claude
   * Code's cloud machines are thrown away when their task's done, without a
   * word (no session end), and their share stops saying it's alive.
   */
  function goneFromCloud(id) {
    const share = shares.find(s => s.id === id);
    return Boolean(share && !share.live && / cloud$/.test(share.host || ""));
  }

  /** What's still open in a session whose cloud machine is gone, ended. */
  const ENDED = new Set(["completed", "failed", "canceled", "input_required"]);
  function ended(node, isSession) {
    if (!node || ENDED.has(node.state)) return node;
    return {
      ...node,
      state: isSession ? "completed" : "canceled",
      busy: false,
      stuck: null,
    };
  }

  // Every session of every share, in the reply from `log`: its own, from
  // the log; the rest, from their shares' summaries. Each says where it is.
  // A session waiting for your reply still is, even once its cloud machine
  // is gone: the rest of it has ended.
  function withOthers(result, log) {
    if (!config.shares || !result || !result.sessions) return result;
    const gone = goneFromCloud(log.id);
    const sessions = {};
    for (const [id, s] of Object.entries(result.sessions))
      sessions[id] = {
        ...(gone && !s.needs_you ? ended(s, true) : s),
        host: hostOf(log.id),
      };
    let nodes = result.nodes;
    if (gone && nodes) {
      nodes = {};
      for (const [id, n] of Object.entries(result.nodes)) {
        const session = id.split("/")[0];
        nodes[id] = result.sessions[session]?.needs_you
          ? n
          : ended(n, id === session);
      }
    }
    const roots = [...(result.roots || [])];
    for (const share of shares) {
      if (share.id === log.id) continue;
      const shareGone = goneFromCloud(share.id);
      for (const [id, s] of Object.entries(share.summary || {})) {
        if (sessions[id]) continue;
        sessions[id] = {
          ...(shareGone && !s.needs_you ? ended(s, true) : s),
          host: share.host,
        };
        roots.push(id);
      }
    }
    return {...result, sessions, nodes, roots};
  }

  // A log being streamed is judged against the clock ("stale?", "5m ago").
  // A pasted one is shown as it stood at its last event.
  const now = () => (config.live ? Date.now() : null);

  window.agentGraphSource = {
    // "site": the graph is shown away from the computer the sessions ran on,
    // so it offers nothing to open. The graph now carries its tree's
    // timeline.
    graph: async (until, root) => {
      const log = logFor(root);
      await log.ready;
      current = log;
      return withOthers(
        await log.reply({
          op: "graph",
          env: "site",
          until: until || null,
          root: root || null,
          now_ms: now(),
        }),
        log,
      );
    },
    info: async () => {
      const info = await current.call({op: "info"});
      return {
        now_ms: config.live ? Date.now() : info.last_event_ms,
        where: null,
      };
    },
    subscribe(onChange, onStatus) {
      onStatus(true);
      if (!config.live) return;
      // Poll gently: every 3 s while events are arriving, backing off to 15 s
      // when quiet or when the tab is hidden. (Only the log being looked at
      // is followed; the other shares' summaries are asked for about every
      // half a minute: they're sent every minute.)
      let delay = 3000;
      let sharesAt = Date.now();
      const tick = async () => {
        try {
          let changed = await current.pull();
          if (config.shares && Date.now() - sharesAt > 30000) {
            sharesAt = Date.now();
            changed = (await loadShares()) || changed;
          }
          if (changed) {
            delay = 3000;
            onChange();
          } else {
            delay = Math.min(delay * 1.5, 15000);
          }
          onStatus(true);
        } catch {
          onStatus(false);
          delay = 10000;
        }
        setTimeout(
          tick,
          typeof document !== "undefined" && document.hidden
            ? Math.max(delay, 15000)
            : delay,
        );
      };
      setTimeout(tick, delay);
      document.addEventListener("visibilitychange", () => {
        if (!document.hidden) delay = 3000;
      });
    },
    imageUrl: null,
    liveLabel: config.live ? "Live" : "Latest",
  };

  const script = document.createElement("script");
  script.src = "/viewer/app.js";
  document.body.appendChild(script);
})().catch(err => {
  const note = document.createElement("p");
  note.className = "banner";
  note.textContent = `Couldn't load this log: ${err.message}`;
  (document.getElementById("view") || document.body).prepend(note);
});
